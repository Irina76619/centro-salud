    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        Paciente p = leerFormulario();
        if (p == null) {
            return;
        }
        if (sistema.pacienteDAO.insertar(p)) {
            JOptionPane.showMessageDialog(this, "Paciente registrado.");
            limpiar();
        } else {
            JOptionPane.showMessageDialog(this, "Ese DNI ya está registrado.");
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (tblPacientes.getSelectedRow() < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un paciente de la tabla.");
            return;
        }
        Paciente datos = leerFormulario();
        if (datos == null) {
            return;
        }

        Paciente p = sistema.pacienteDAO.buscar(datos.getDni());   
        p.setNombre(datos.getNombre());
        p.setApellidos(datos.getApellidos());
        p.setEdad(datos.getEdad());
        p.setTelefono(datos.getTelefono());
        sistema.pacienteDAO.actualizar(p);

        JOptionPane.showMessageDialog(this, "Paciente actualizado.");
        limpiar();
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = tblPacientes.getSelectedRow();
        if (fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un paciente de la tabla.");
            return;
        }
        Paciente p = sistema.pacienteDAO.buscar((String) modelo.getValueAt(fila, 0));
        if (!sistema.citaDAO.listarPorPaciente(p).isEmpty()) {          // RN-12
            JOptionPane.showMessageDialog(this, "No se puede eliminar: el paciente tiene citas.");
            return;
        }
        int r = JOptionPane.showConfirmDialog(this, "¿Eliminar a " + p.getNombreCompleto() + "?",
                "Confirmar", JOptionPane.YES_NO_OPTION);
        if (r == JOptionPane.YES_OPTION) {
            sistema.pacienteDAO.eliminar(p.getDni());
            limpiar();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

