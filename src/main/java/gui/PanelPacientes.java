    private void cargarTabla() {
        mostrar(sistema.pacienteDAO.listar());
    }

    private void mostrar(java.util.List<Paciente> lista) {
        modelo.setRowCount(0);
        for (Paciente p : lista) {
            modelo.addRow(new Object[]{p.getDni(), p.getNombre(), p.getApellidos(),
                p.getEdad(), p.getTelefono()});
        }
    }

    private void limpiar() {
        txtDni.setText("");
        txtNombre.setText("");
        txtApellidos.setText("");
        txtEdad.setText("");
        txtTelefono.setText("");
        txtDni.setEditable(true);
        tblPacientes.clearSelection();
        cargarTabla();
    }

    /**
     * Valida los campos (RN-08) y devuelve un Paciente, o null si hay error.
     */
    private Paciente leerFormulario() {
        String dni = txtDni.getText().trim();
        String nombre = txtNombre.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String telefono = txtTelefono.getText().trim();

        if (!dni.matches("\\d{8}")) {
            JOptionPane.showMessageDialog(this, "El DNI debe tener 8 dígitos.");
            return null;
        }
        if (nombre.isEmpty() || apellidos.isEmpty() || telefono.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return null;
        }
        int edad;
        try {
            edad = Integer.parseInt(txtEdad.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La edad debe ser un número.");
            return null;
        }
        if (edad < 0 || edad > 120) {
            JOptionPane.showMessageDialog(this, "La edad debe estar entre 0 y 120.");
            return null;
        }
        return new Paciente(dni, nombre, apellidos, edad, telefono);
    }

    private void resultadoBusqueda(Paciente p) {
        if (p == null) {
            JOptionPane.showMessageDialog(this, "Paciente no encontrado.");
            return;
        }
        mostrar(java.util.List.of(p));
    }

